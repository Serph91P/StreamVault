import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const frontendRoot = resolve(import.meta.dirname, '..')
const argument = name => {
  const index = process.argv.indexOf(name)
  return index === -1 ? undefined : process.argv[index + 1]
}
const responsiveSourcePath = resolve(frontendRoot, 'src/styles/responsive.tokens.json')
const responsiveOutputs = {
  sass: resolve(frontendRoot, 'src/styles/_responsive.generated.scss'),
  typeScript: resolve(frontendRoot, 'src/composables/layoutQueries.generated.ts'),
}
const designSourcePath = resolve(argument('--design-source') || resolve(frontendRoot, 'src/styles/design.tokens.json'))
const designOutputPath = resolve(argument('--design-output') || resolve(frontendRoot, 'src/styles/_foundation.generated.scss'))

function assertRecord(value, name) {
  if (!value || typeof value !== 'object' || Array.isArray(value)) throw new Error(`${name} must be an object`)
}

function validateResponsiveTokens(tokens) {
  assertRecord(tokens, 'responsive tokens')
  assertRecord(tokens.breakpoints, 'breakpoints')
  assertRecord(tokens.queries, 'queries')
  const widths = Object.entries(tokens.breakpoints)
  if (widths.length === 0 || widths.some(([name, value]) => !name || !Number.isInteger(value) || value <= 0)) {
    throw new Error('breakpoints must contain positive integer pixel values')
  }
  for (let index = 1; index < widths.length; index += 1) {
    if (widths[index - 1][1] >= widths[index][1]) throw new Error('breakpoints must be strictly ascending')
  }
  if (Object.values(tokens.queries).some(query => typeof query !== 'string' || !query.startsWith('(') || !query.endsWith(')'))) {
    throw new Error('queries must contain media-query strings')
  }
}

function flatten(value, prefix = [], target = new Map()) {
  if (typeof value === 'string' || typeof value === 'number') {
    target.set(prefix.join('.'), String(value))
    return target
  }
  assertRecord(value, prefix.join('.') || 'design tokens')
  for (const key of Object.keys(value).sort()) flatten(value[key], [...prefix, key], target)
  return target
}

const REFERENCE = /\{([^}]+)\}/g
function validateReferences(flat) {
  const visiting = new Set()
  const visited = new Set()
  function visit(path) {
    if (visiting.has(path)) throw new Error(`circular token reference: ${[...visiting, path].join(' -> ')}`)
    if (visited.has(path)) return
    const value = flat.get(path)
    if (value === undefined) throw new Error(`undefined token reference: ${path}`)
    visiting.add(path)
    for (const match of value.matchAll(REFERENCE)) visit(match[1])
    visiting.delete(path)
    visited.add(path)
  }
  for (const path of flat.keys()) visit(path)
}

function cssName(path) {
  const parts = path.split('.')
  const group = parts.shift()
  if (group === 'foundation') return `--sv-fdn-${parts.join('-')}`
  if (group === 'semanticDark' || group === 'semanticLight' || group === 'semantic') return `--sv-sem-${parts.join('-')}`
  if (group === 'component') return `--sv-cmp-${parts.join('-')}`
  return `--sv-${[group, ...parts].join('-')}`
}

function cssValue(value) {
  return value.replace(REFERENCE, (_, path) => `var(${cssName(path)})`)
}

function declarations(flat, groups) {
  return [...flat.entries()]
    .filter(([path]) => groups.includes(path.split('.')[0]))
    .map(([path, value]) => `  ${cssName(path)}: ${cssValue(value)};`)
    .join('\n')
}

function renderDesignTokens(tokens) {
  const flat = flatten(tokens)
  validateReferences(flat)
  const rootGroups = flat.has('semantic.text') ? ['foundation', 'semantic', 'component'] : ['foundation', 'semanticDark', 'component']
  const light = declarations(flat, ['semanticLight'])
  return `// Generated by scripts/generate-responsive-tokens.mjs from design.tokens.json. Do not edit.\n\n:root {\n${declarations(flat, rootGroups)}\n}\n${light ? `\n[data-theme="light"] {\n${light}\n}\n` : ''}`
}

function renderResponsiveSass(tokens) {
  const breakpoints = Object.entries(tokens.breakpoints).map(([name, value]) => `  '${name}': ${value}px`).join(',\n')
  return `// Generated by scripts/generate-responsive-tokens.mjs. Do not edit.\n\n$breakpoints: (\n${breakpoints}\n);\n`
}

function renderResponsiveTypeScript(tokens) {
  const queries = Object.entries(tokens.queries).map(([name, query]) => `  ${name}: '${query}',`).join('\n')
  return `// Generated by scripts/generate-responsive-tokens.mjs. Do not edit.\n\nexport const layoutQueries = {\n${queries}\n} as const\n\nexport type LayoutQueryName = keyof typeof layoutQueries\n`
}

async function checkOrWrite(path, expected, label, check) {
  if (check) {
    let actual
    try { actual = await readFile(path, 'utf8') } catch { actual = undefined }
    if (actual !== expected) throw new Error(`${label} generated output is stale: ${path}`)
  } else {
    await writeFile(path, expected)
  }
}

const check = process.argv.includes('--check')
const designOnly = process.argv.includes('--design-source') || process.argv.includes('--design-output')
const designTokens = JSON.parse(await readFile(designSourcePath, 'utf8'))
await checkOrWrite(designOutputPath, renderDesignTokens(designTokens), 'design', check)

if (!designOnly) {
  const responsiveTokens = JSON.parse(await readFile(responsiveSourcePath, 'utf8'))
  validateResponsiveTokens(responsiveTokens)
  await checkOrWrite(responsiveOutputs.sass, renderResponsiveSass(responsiveTokens), 'responsive', check)
  await checkOrWrite(responsiveOutputs.typeScript, renderResponsiveTypeScript(responsiveTokens), 'responsive', check)
}
console.log(check ? 'design and responsive generated output is current' : 'generated design, responsive Sass and TypeScript owners')
