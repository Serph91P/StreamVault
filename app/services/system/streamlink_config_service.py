"""
Streamlink Configuration Service

This service automatically generates Streamlink configuration files
based on application settings (OAuth token, proxy, codecs, etc.)

The config file is created at application startup and updated whenever
settings change.
"""

import logging
import asyncio
from collections.abc import Callable
from pathlib import Path
from typing import Optional
from sqlalchemy.orm import Session
from app.utils.async_db_utils import run_in_thread_pool

logger = logging.getLogger("streamvault")


class StreamlinkConfigService:
    """Manages automatic generation of Streamlink configuration files"""

    def __init__(
        self,
        *,
        config_dir: str | Path = "/app/config/streamlink",
        session_factory: Callable[[], Session] | None = None,
    ):
        self.config_dir = Path(config_dir)
        self.twitch_config_path = self.config_dir / "config.twitch"
        self.twitch_anonymous_config_path = self.config_dir / "config.twitch-anonymous"
        self._session_factory = session_factory
        self._update_lock = asyncio.Lock()

    def generate_twitch_config(
        self,
        oauth_token: Optional[str] = None,
        http_proxy: Optional[str] = None,
        https_proxy: Optional[str] = None,
        supported_codecs: str = "av1,h265,h264",
    ) -> bool:
        """
        Generate Twitch plugin configuration file for Streamlink.

        This config contains static Streamlink options that don't change per-recording:
        - Codec preferences (h265, av1, h264)
        - Ad blocking settings

        Credentials, proxy settings, quality, and output paths are passed via
        command-line for each new process.

        Args:
            oauth_token: Ignored; credentials are selected for each new process
            http_proxy: Ignored; proxies are passed to each new process
            https_proxy: Ignored; proxies are passed to each new process
            supported_codecs: Comma-separated codec list (default: av1,h265,h264)

        Returns:
            True if config was successfully written, False otherwise
        """
        try:
            config_lines = [
                "# Streamlink Twitch Plugin Configuration",
                "# Auto-generated by StreamVault - DO NOT EDIT MANUALLY",
                "# This file is regenerated on application startup",
                "",
                "# Codec preferences (enables H.265/AV1 for better quality)",
                f"twitch-supported-codecs={supported_codecs}",
                "",
            ]

            # OAuth token is ALWAYS passed via CLI (--twitch-api-header)
            # Do NOT add it to config file to avoid duplicate headers
            config_lines.extend(
                [
                    "# Twitch OAuth Authentication",
                    "# Token is passed via CLI argument (--twitch-api-header) per recording",
                    "# This ensures we always use the freshest auto-refreshed token",
                    "# DO NOT add twitch-api-header here - it causes duplicate headers!",
                    "",
                ]
            )

            logger.debug("OAuth credentials and proxies are selected per child")

            # Add static Streamlink options (from get_streamlink_command)
            config_lines.extend(
                [
                    "# Stream stability settings",
                    "hls-live-edge=3",
                    "stream-timeout=200",
                    "stream-segment-timeout=200",
                    "stream-segment-threads=5",
                    "retry-streams=10",
                    "retry-max=2",
                    "",
                    "# FFmpeg output format",
                    "ffmpeg-fout=mpegts",
                    "",
                    "# Logging configuration",
                    "loglevel=debug",
                    "logformat=[{asctime}][{name}][{levelname}] {message}",
                    "logdateformat=%Y-%m-%d %H:%M:%S",
                    "",
                    "# NOTE: Quality, output path, and log file path are set via command-line",
                    "# because they change per-recording and per-streamer",
                ]
            )

            # Write config file
            config_content = "\n".join(config_lines)

            # Skip if directory doesn't exist (permission issue during init)
            if not self.config_dir.exists():
                logger.warning(
                    "⚠️ Config directory doesn't exist - skipping config file write"
                )
                logger.warning("   Using command-line arguments only")
                return False

            with open(self.twitch_config_path, "w", encoding="utf-8") as f:
                f.write(config_content)

            anonymous_config_path = getattr(
                self,
                "twitch_anonymous_config_path",
                self.twitch_config_path.with_name("config.twitch-anonymous"),
            )
            anonymous_config_content = config_content.replace(
                f"twitch-supported-codecs={supported_codecs}",
                "twitch-supported-codecs=h264",
                1,
            )
            with open(anonymous_config_path, "w", encoding="utf-8") as f:
                f.write(anonymous_config_content)

            logger.info(
                f"✅ Streamlink Twitch config generated: {self.twitch_config_path}"
            )
            logger.debug(f"📝 Config size: {len(config_content)} bytes")

            return True

        except PermissionError:
            logger.warning(f"⚠️ No permission to write {self.twitch_config_path}")
            logger.warning(
                "   Check docker-compose.yml volume mount (should NOT be :ro)"
            )
            return False
        except (OSError, IOError) as e:
            logger.error(f"❌ Failed to write streamlink config: {e}")
            logger.error(f"   Config path: {self.twitch_config_path}")
            return False
        except Exception as e:
            logger.error(f"❌ Unexpected error generating streamlink config: {e}")
            return False

    async def update_config_from_settings(self) -> bool:
        """Write static codec files from a closed owning DB scope, off loop.

        OAuth/proxy values belong to each child command; generating these static
        files must not acquire or refresh credentials over the network.
        """
        from app.database import SessionLocal
        from app.models import GlobalSettings

        def update() -> bool:
            with (self._session_factory or SessionLocal)() as db:
                row = db.query(GlobalSettings).first()
                codecs = (row.supported_codecs if row else None) or "av1,h265,h264"
            self.config_dir.mkdir(parents=True, exist_ok=True)
            return self.generate_twitch_config(supported_codecs=codecs)

        try:
            async with self._update_lock:
                return await run_in_thread_pool(update)
        except Exception as error:
            logger.error(
                "Failed to update Streamlink configuration (%s)", type(error).__name__
            )
            return False

    async def regenerate_config(self) -> bool:
        """
        Force regeneration of Streamlink config from current settings.

        Called when user updates settings that affect Streamlink:
        - Proxy settings changed
        - Codec preferences changed
        - OAuth token refreshed

        Returns:
            True if config was successfully regenerated
        """
        logger.info("🔄 Regenerating Streamlink config from updated settings...")
        success = await self.update_config_from_settings()

        if success:
            logger.info("✅ Streamlink config regenerated successfully")
        else:
            logger.error("❌ Failed to regenerate Streamlink config")

        return success

